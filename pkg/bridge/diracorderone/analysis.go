// Package diracorderone implements Gate 164: finite Dirac candidate
// construction / order-one axiom obstruction audit.
//
// Gate 163 proved that exact spectral pre-data exist, but that no finite
// spectral action is lawful until a spectral triple is constructed. Gate 164
// asks the next narrower question: can any currently available finite operator
// be promoted to a nontrivial Dirac operator satisfying the order-one axiom?
//
// The answer is again conservative. Contact-only choices built from the exact
// contact overlap Omega are order-one-safe only in the vacuous sense: for the
// commutative spectral algebra generated by Omega, all commutators vanish and
// therefore the first-order condition has no content and no gauge fluctuation.
// Every nontrivial mixed-sector candidate requires a missing canonical algebra
// representation, real structure J, grading gamma, or sector map. Hence no
// physical beta row, action coefficient, mass, scale, or coupling is opened.
