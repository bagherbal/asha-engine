func FormatDiracList(items []DiracConstruction) string {
	parts := make([]string, 0, len(items))
	for _, item := range items {
		parts = append(parts, fmt.Sprintf("%s(order1=%t,vacuous=%t,promotable=%t)", item.Name, item.OrderOneVerified, item.OrderOneVacuous, item.PromotableToFiniteDirac))
	}
	sort.Strings(parts)
	return strings.Join(parts, "; ")
}
