func auditOrderOne(items []DiracConstruction) OrderOneAudit {
	a := OrderOneAudit{DiracCandidatesAudited: len(items), Verdict: "order-one succeeds only for gauge-trivial contact spectral functions; nontrivial Dirac blocks remain untestable and unpromotable"}
	for _, item := range items {
		if item.ExactOverQ {
			a.ExactCandidates++
		}
		if item.SelfAdjoint {
			a.SelfAdjointCandidates++
		}
		if item.FiniteSpectrum {
			a.FiniteSpectrumCandidates++
		}
		if item.GaloisInvariant {
			a.GaloisInvariantCandidates++
		}
		if item.BranchFree {
			a.BranchFreeCandidates++
		}
		if item.UsesObservedInput {
			a.ObservedInputsUsed = true
		}
		if item.UsesBranchChoice {
			a.BranchChoicesUsed++
		}
		if item.RepresentationCanonical {
			a.RepresentationCanonical++
		}
		if item.RealStructureCanonical {
			a.RealStructureCanonical++
		}
		if item.GradingCanonical {
			a.GradingCanonical++
		}
		if item.TotalHilbertCompatible {
			a.TotalHilbertCompatible++
		}
		if item.OrderOneTestable {
			a.OrderOneTestable++
		}
		if item.OrderOneVerified {
			a.OrderOneVerified++
		}
		if item.OrderOneVacuous {
			a.OrderOneVacuous++
		}
		if item.NontrivialCommutators {
			a.NontrivialCommutatorCandidates++
		}
		if item.NontrivialCommutators && item.OrderOneVerified {
			a.NontrivialOrderOneVerified++
		}
		if item.GaugeFluctuationNontrivial {
			a.GaugeFluctuationNontrivial++
		}
		if item.GaugeFluctuationTrivial {
			a.GaugeFluctuationTrivial++
		}
		if item.RequiresAlgebraRep {
			a.RequiresAlgebraRep++
		}
		if item.RequiresRealStructure {
			a.RequiresRealStructure++
		}
		if item.RequiresGrading {
			a.RequiresGrading++
		}
		if item.RequiresSectorMap {
			a.RequiresSectorMap++
		}
		if item.RequiresBranchBreaking {
			a.RequiresBranchBreaking++
		}
		if item.PromotableToFiniteDirac {
			a.PromotableFiniteDirac++
		}
		a.GaugeKineticMapRows += item.GaugeKineticMapRows
		a.BoundaryConstraintsDerived += item.BoundaryConstraintsDerived
		a.ThresholdBetaRows += item.ThresholdBetaRows
		if item.PhysicalConstantsDerived {
			a.PhysicalConstantsDerived = true
		}
	}
	return a
}

