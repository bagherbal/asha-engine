func auditRepresentations(items []RepresentationCandidate) RepresentationAudit {
	a := RepresentationAudit{CandidatesAudited: len(items), Verdict: "only the contact spectral representation is canonical, and it is gauge-trivial; no faithful total representation is available"}
	for _, item := range items {
		if item.Available {
			a.AvailableCandidates++
		}
		if item.Canonical {
			a.CanonicalCandidates++
		}
		if item.FaithfulOnTotalHilbert {
			a.FaithfulTotalRepresentations++
		}
		if item.Commutative {
			a.CommutativeCandidates++
		}
		if item.GeneratesNonzeroOneForms {
			a.NonzeroOneFormCandidates++
		}
		if item.GaugeFluctuationTrivial {
			a.GaugeTrivialCandidates++
		}
		if item.RequiresBranchChoice {
			a.BranchChoicesUsed++
		}
		if item.UsesObservedInput {
			a.ObservedInputsUsed = true
		}
	}
	return a
}

